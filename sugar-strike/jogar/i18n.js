  window.SugarI18n = {
    SUPPORTED: ["pt", "en", "es", "fr", "zh", "hi", "ar", "bn", "ru", "ur"],
    LANG_NAMES: LANG_NAMES,
    MODE_KEYS: MODE_KEYS,
    MAP_KEYS: MAP_KEYS,
    ROLE_KEYS: ROLE_KEYS,
    TEAM_KEYS: TEAM_KEYS,
    _tableFor: tr,
    _all: S,
    detect: function () {
      var stored = null;
      try { stored = localStorage.getItem(LANG_KEY); } catch (e) {}
      if (stored && S[stored]) return stored;
      var nav = (navigator.language || navigator.userLanguage || "pt").toLowerCase();
      var code = nav.split("-")[0];
      if (S[code]) return code;
      return "en";
    },
    get: function () {
      if (!this._current) this._current = this.detect();
      return this._current;
    },
    set: function (lang) {
      if (!S[lang]) return;
      this._current = lang;
      try { localStorage.setItem(LANG_KEY, lang); } catch (e) {}
      try {
        document.documentElement.lang = lang;
        document.documentElement.dir = RTL_LANGS[lang] ? "rtl" : "ltr";
      } catch (e) {}
    },
    t: function (key, vars) {
      var lang = this.get();
      var table = S[lang] || S.pt;
      var value = table[key];
      if (value === undefined) value = S.pt[key];
      if (value === undefined) return key;
      if (vars) {
        for (var k in vars) {
          value = value.split("{" + k + "}").join(String(vars[k]));
        }
      }
      return value;
    },
    modeLabel: function (mode) { return this.t(MODE_KEYS[mode] || "MODE_DEATHMATCH"); },
    mapLabel: function (map) { return this.t(MAP_KEYS[map] || "MAP_VILLAGE"); },
    roleLabel: function (role) { return this.t(ROLE_KEYS[role] || role); },
    teamLabel: function (team) { return team === 1 ? this.t("TEAM_1") : (team === 2 ? this.t("TEAM_2") : this.t("NET_NO_TEAM")); },
    applyStatic: function () {
      document.querySelectorAll("[data-i18n]").forEach(function (element) {
        var key = element.getAttribute("data-i18n");
        element.textContent = window.SugarI18n.t(key);
      });
      document.querySelectorAll("[data-i18n-html]").forEach(function (element) {
        var key = element.getAttribute("data-i18n-html");
        element.innerHTML = window.SugarI18n.t(key);
      });
      document.querySelectorAll("[data-i18n-placeholder]").forEach(function (element) {
        var key = element.getAttribute("data-i18n-placeholder");
        element.setAttribute("placeholder", window.SugarI18n.t(key));
      });
    }
  };
  window.SugarI18n.set(window.SugarI18n.get());
